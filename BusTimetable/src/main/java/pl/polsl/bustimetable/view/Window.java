    /**
     * Handles clicking the button to show the bus stop timetable.
     * It gets the input from textFieldShowBusStopTimetable. 
     * If it is empty, it displays a warning by popupWarning and ends the method. 
     * Gets a 2D array containing data of the desired bus stop from the controller.
     * If the array is not null, it sets the model for the table 'timetable' with 
     * data 'data' and column names in String[].
     * Then it opens a new window and closes the previous one.
     * If this array is null, it means that user
     * provided wrong bus stop name and program shows that by popupError.
     * 
     * AI-assisted code:
     * AI helped with using DefaultTableModel to display data
     * from a 2D array in a JTable with specified column names.
     * 
     * @param evt the event triggered by clicking the button
     */
    private void buttonShowBusStopTimetableActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonShowBusStopTimetableActionPerformed
        String name = textFieldShowBusStopTimetable.getText();
        
        if(name.isBlank()){
            popupWarning("Please enter bus stop name to show!");
            return;
        }
        
        Object[][] data = controllerWindow.showBusStopTimetable(name);

        if (data != null) {
            timetable.setModel(new DefaultTableModel(
                data,
                new String[]{"Bus line", "Departure times"}
            ));

            busStopNameToShow.setText("Showing timetable for bus stop: " + name);

            showBusStopTimetableWindow.dispose();
            busStopTimetableWindow.setVisible(true);
        } else {
            popupError("Bus stop does not exist!");
        }
    }//GEN-LAST:event_buttonShowBusStopTimetableActionPerformed

